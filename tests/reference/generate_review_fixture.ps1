$ErrorActionPreference='Stop'
& (Join-Path $PSScriptRoot 'build_reference.ps1')
$root=Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$exe=Join-Path $root 'build/monero-reference/monero_reference.exe'
$rows=& $exe --review-fixture
if($LASTEXITCODE -ne 0){throw 'Reference review proof failed'}
$data=[ordered]@{}
foreach($row in $rows){$pair=$row -split '=',2; if(!$pair[0].StartsWith('generator_')){$data[$pair[0]]=$pair[1]}}
if($data.accepted -ne '1'){throw 'Reference rejected review proof'}
$data.source='monero-project/monero v0.18.4.0 f1311d4237404ab7da76241dbf10e92a65132cc4'
$data.parameters='monero_reference --review-fixture; public test keys, 2 outputs of 400000000000 atomic units; deterministic fixture skGen. TEST ONLY.'
$json=($data | ConvertTo-Json -Depth 4)+"`n"
[IO.File]::WriteAllText((Join-Path $root 'tests/fixtures/monero-bp-plus/review.json'),$json,[Text.UTF8Encoding]::new($false))
function KeyArray([string]$hex){
  $bytes=for($i=0;$i -lt 32;$i++){'0x'+$hex.Substring($i*2,2)}
  return '{'+($bytes -join ',')+'}'
}
$lines=@('// Generated by tests/reference/generate_review_fixture.ps1. TEST ONLY.',
  '// Independent pinned Monero prover output; public masks and test keys.',
  ('// SHA256(review.json): '+(Get-FileHash (Join-Path $root 'tests/fixtures/monero-bp-plus/review.json')).Hash.ToLowerInvariant()),'{')
foreach($field in @('A','A1','B','r1','s1','d1')){$lines+=(KeyArray $data[$field])+','}
$lines+="$($data.rounds), $($data.rounds),"
foreach($field in @('L','R')){
  $lines+='{' ; for($i=0;$i -lt [int]$data.rounds;$i++){$lines+=(KeyArray $data["${field}_$i"])+','}; $lines+='},'
}
$lines+='}'
[IO.File]::WriteAllText((Join-Path $root 'src/generated/MoneroReviewProofTest.inc'),($lines -join "`n")+"`n",[Text.UTF8Encoding]::new($false))
