#!/usr/bin/env python3
"""Independent two-member CLSAG arithmetic vector, NOT an on-chain transaction.

The public keys and key images are Monero tests/crypto/tests.txt vectors also
used by CryptoNoteRingCt.cpp. Recovering Hp(P)=I/p avoids reusing the firmware's
nonstandard hash-to-point implementation. Python integer arithmetic and
PyCryptodome Keccak implement the CLSAG transcript independently.
Requires pycryptodome==3.23.0. See Monero v0.18.4.0 rctSigs.cpp CLSAG_Gen.
"""
import argparse
from generate_ringct_amount_vectors import ROOT, L, G, hs, scalar, point, add, mul, commitment


def encoded(p):
    x, y = p
    return scalar(y | ((x & 1) << 255))


def render():
    public = [
        "e46b60ebfe610b8ba761032018471e5719bb77ea1cd945475c4a4abe7224bfd0",
        "8661153f5f856b46f83e9e225777656cd95584ab16396fa03749ec64e957283b"]
    secrets = [
        "981d477fb18897fa1f784c89721a9d600bf283f06b89cb018a077f41dcefef0f",
        "156d7f2e20899371404b87d612c3587ffe9fba294bafbbc99bb1695e3275230e"]
    images = [
        "a637203ec41eab772532d30420eac80612fce8e44f1758bc7e2cb1bdda815887",
        "03ec63d7f1b722f551840b2725c76620fa457c805cbbf2ee941a6bf4cfb6d06c"]
    p = [int.from_bytes(bytes.fromhex(s), "little") for s in secrets]
    hp = [mul(pow(p[i], -1, L), point(images[i])) for i in range(2)]
    for i in range(2):
        assert encoded(mul(p[i], G)).hex() == public[i]
        assert encoded(mul(p[i], hp[i])).hex() == images[i]
    commitments = [commitment(10, 100), commitment(11, 100)]
    offset = commitment(7, 100)
    z, alpha, decoy_s = 3, 5, 9
    image = bytes.fromhex(images[0])
    auxiliary_full = mul(z, hp[0])
    auxiliary = encoded(mul(pow(8, -1, L), auxiliary_full))
    keys = b"".join(bytes.fromhex(v) for v in public) + b"".join(commitments)
    mu_p = hs(b"CLSAG_agg_0".ljust(32, b"\0") + keys + image + auxiliary + offset)
    mu_c = hs(b"CLSAG_agg_1".ljust(32, b"\0") + keys + image + auxiliary + offset)
    message = scalar(hs(b"HexWallet independent CLSAG reference"))

    def challenge(left, right):
        return hs(b"CLSAG_round".ljust(32, b"\0") + keys + offset + message + encoded(left) + encoded(right))

    c_decoy = challenge(mul(alpha, G), mul(alpha, hp[0]))
    # C_decoy - offset = (11-7)*G; amounts cancel.
    left = add(mul(decoy_s, G), mul(c_decoy, add(mul(mu_p, point(public[1])), mul(mu_c * 4 % L, G))))
    right = add(mul(decoy_s, hp[1]), mul(c_decoy, add(mul(mu_p, point(images[0])), mul(mu_c, auxiliary_full))))
    c_real = challenge(left, right)
    s_real = (alpha - c_real*(mu_p*p[0] + mu_c*z)) % L
    # Independently close the ring equation before emitting a fixture.
    left_real = add(mul(s_real, G), mul(c_real, add(mul(mu_p, point(public[0])), mul(mu_c*z % L, G))))
    right_real = add(mul(s_real, hp[0]), mul(c_real, add(mul(mu_p, point(images[0])), mul(mu_c, auxiliary_full))))
    assert challenge(left_real, right_real) == c_decoy
    values = [message.hex(), offset.hex(), auxiliary.hex(), scalar(c_real).hex(), scalar(s_real).hex(), scalar(decoy_s).hex(), commitments[0].hex(), commitments[1].hex()]
    return ("// Independent two-member arithmetic fixture; not a network-valid transaction.\n"
            "// Generated by tools/generate_clsag_reference_vector.py.\n"
            "const char *const kClsagReference[] = {\n" +
            "".join('  "%s",\n' % value for value in values) + "};\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "src/generated/ClsagReferenceVectorTest.inc"
    expected = render()
    if args.check:
        if path.read_text(encoding="utf-8") != expected:
            raise SystemExit("CLSAG reference vector is stale")
    else:
        path.write_text(expected, encoding="utf-8")
