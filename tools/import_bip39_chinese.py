"""Pin the two BIP39 Chinese wordlists and emit the firmware tables."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def main():
    revision = (ROOT / "assets/wordlists/revision.txt").read_text().strip()
    assert len(revision) == 40 and all(c in "0123456789abcdef" for c in revision)
    records, output = [], ["// BIP39 lists; generated by tools/import_bip39_chinese.py."]
    for name, symbol in [("chinese_simplified", "kBip39Simplified"), ("chinese_traditional", "kBip39Traditional")]:
        url = f"https://raw.githubusercontent.com/bitcoin/bips/{revision}/bip-0039/{name}.txt"
        data = (ROOT / f"assets/wordlists/{name}.txt").read_bytes()
        words = data.decode("utf-8").splitlines()
        assert len(words) == len(set(words)) == 2048
        assert all(len(w) == 1 and 0x4e00 <= ord(w) <= 0x9fff for w in words)
        output.append(f"static const char *const {symbol}[2048] = {{")
        output.extend('  "' + w + '",' for w in words)
        output.append("};")
        records.append(dict(language=name, url=url, sha256=hashlib.sha256(data).hexdigest()))
    (ROOT / "src/generated/Bip39Chinese.inc").write_text("\n".join(output) + "\n", encoding="utf-8")
    (ROOT / "assets/fonts/bip39-sources.json").write_text(json.dumps(records, indent=2) + "\n", encoding="utf-8")

if __name__ == "__main__":
    main()
