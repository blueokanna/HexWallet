#!/usr/bin/env python3
"""Independent amount/commitment vectors, not transaction or range-proof vectors.

Requires pycryptodome==3.23.0. Uses Python integer Edwards arithmetic and
PyCryptodome Keccak; never imports or calls the firmware implementation.
Reference algorithms: Monero v0.18.4.0 src/ringct/rctOps.cpp, ecdhEncode,
genCommitmentMask; Masari src/ringct/rctOps.cpp, ecdhEncode (legacy only).
"""
from pathlib import Path
import argparse
from Crypto.Hash import keccak

ROOT = Path(__file__).resolve().parents[1]
P = 2**255 - 19
L = 2**252 + 27742317777372353535851937790883648493
D = -121665 * pow(121666, -1, P) % P


def digest(data):
    return keccak.new(digest_bits=256, data=data).digest()


def scalar(value):
    return value.to_bytes(32, "little")


def hs(data):
    return int.from_bytes(digest(data), "little") % L


def point(encoded):
    raw = int.from_bytes(bytes.fromhex(encoded), "little")
    y = raw & (2**255 - 1)
    x2 = (y*y-1) * pow(D*y*y+1, -1, P) % P
    x = pow(x2, (P+3)//8, P)
    if x*x % P != x2:
        x = x * pow(2, (P-1)//4, P) % P
    assert x*x % P == x2
    if x % 2 != raw >> 255:
        x = P-x
    return x, y


def add(a, b):
    x, y = a
    u, v = b
    t = D*x*u*y*v % P
    return ((x*v+y*u)*pow(1+t, -1, P) % P,
            (y*v+x*u)*pow(1-t, -1, P) % P)


def mul(n, a):
    result = (0, 1)
    while n:
        if n & 1:
            result = add(result, a)
        a = add(a, a)
        n >>= 1
    return result


G = point("58" + "66"*31)
H = point("8b655970153799af2aeadc9ff1add0ea6c7251d54154cfa92c173a0dd39c1f94")


def commitment(mask, amount):
    x, y = add(mul(mask, G), mul(amount, H))
    return scalar(y | ((x & 1) << 255))


def render():
    # Independent check against Monero's precomputed zeroCommit(1)=G+H.
    assert commitment(1, 1).hex() == (
        "1738eb7a677c6149228a2beaa21bea9e3370802d72a3eec790119580e02bd522")
    lines = ["// Generated by tools/generate_ringct_amount_vectors.py.\n",
             "// Independent reference vectors; no complete transaction is represented.\n"]
    for compact in (False, True):
        for index, amount in enumerate((0, 1, 10**12, 2**64-1)):
            key = scalar(hs(b"HexWallet amount reference " + bytes([index])))
            mask = hs(b"commitment_mask" + key) if compact else (0 if index == 0 else L-1-index)
            if compact:
                encoded = bytes(a ^ b for a, b in zip(amount.to_bytes(8, "little"), digest(b"amount" + key)))
            else:
                first = hs(key)
                second = hs(scalar(first))
                encoded = scalar((mask+first) % L) + scalar((amount+second) % L)
            mode = "Compact" if compact else "Legacy"
            lines.append('  {RingCtAmountEncoding::%s, UINT64_C(%d), "%s", "%s", "%s", "%s"},\n' %
                         (mode, amount, key.hex(), scalar(mask).hex(), encoded.hex(), commitment(mask, amount).hex()))
    return "".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "src/generated/RingCtAmountVectors.inc"
    expected = render()
    if args.check:
        if path.read_text(encoding="utf-8") != expected:
            raise SystemExit("RingCT amount vectors are stale")
    else:
        path.write_text(expected, encoding="utf-8")
