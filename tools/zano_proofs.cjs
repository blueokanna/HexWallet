'use strict';
// Ordinary Zarcanum outputs. Transcripts and generator ordering follow Zano
// b5430539, range_proof_bpp.h, one_out_of_many_proofs.cpp and zarcanum.cpp.
const {ed25519} = require('@noble/curves/ed25519');
const {hs, sc, randomScalar} = require('./ryo_bulletproof.cjs');
const {X, U, bpGenerator, bgeGenerator} = require('./zano_verify.cjs');
const Point = ed25519.Point, F = Point.Fn, G = Point.BASE;
const inverseEight = F.inv(8n);
const encodeCommitment = point => point.multiply(inverseEight).toBytes();
const msm = (points, scalars) => Point.msm(points, scalars.map(s => F.create(s)));

function proveRange(amounts, masks, commitments) {
  const n = 64 * 2 ** Math.ceil(Math.log2(amounts.length));
  let g = Array.from({length:n}, (_, i) => bpGenerator(2*i));
  let h = g.map((_, i) => bpGenerator(2*i+1));
  let a = g.map((_, i) => ((amounts[i >> 6] ?? 0n) >> BigInt(i % 64)) & 1n);
  let b = a.map(bit => bit - 1n);
  let alpha = randomScalar();
  const a0 = encodeCommitment(msm([...g, ...h, G], [...a, ...b, alpha]));
  const initial = hs(sc(hs(Buffer.from('Zano BP+ initial transcript'))), ...commitments);
  const y = hs(sc(initial), a0), z = hs(sc(y));
  const powers = [1n];
  for (let i = 0; i <= n; ++i) powers.push(F.mul(powers[i], y));
  let transcript = z, zPower = 1n;
  for (let i = 0; i < n; ++i) {
    if (i % 64 === 0) {
      zPower = F.mul(zPower, F.sqr(z));
      alpha = F.create(alpha + powers[n+1] * zPower * (masks[i >> 6] ?? 0n));
    }
    const d = zPower << BigInt(i % 64);
    a[i] = F.sub(a[i], z);
    b[i] = F.create(b[i] + z + d * powers[n-i]);
  }
  const left = [], right = [];
  while (a.length > 1) {
    const half = a.length / 2, yHalf = powers[half], inverse = F.inv(yHalf);
    const a1 = a.slice(0, half), a2 = a.slice(half), b1 = b.slice(0, half), b2 = b.slice(half);
    const g1 = g.slice(0, half), g2 = g.slice(half), h1 = h.slice(0, half), h2 = h.slice(half);
    const cross = (u, v) => F.create(u.reduce((sum, t, i) => sum + t * powers[i+1] * v[i], 0n));
    const dL = randomScalar(), dR = randomScalar();
    const l = encodeCommitment(msm([...g2, ...h1, U, G], [...a1.map(v => v*inverse), ...b2, cross(a1,b2), dL]));
    const r = encodeCommitment(msm([...g1, ...h2, U, G], [...a2.map(v => v*yHalf), ...b1, cross(a2,b1)*yHalf, dR]));
    left.push(l); right.push(r);
    const e = hs(sc(transcript), l, r), ei = F.inv(e);
    transcript = e;
    g = g1.map((p, i) => msm([p,g2[i]], [ei,e*inverse]));
    h = h1.map((p, i) => msm([p,h2[i]], [e,ei]));
    a = a1.map((v, i) => F.create(e*v + ei*yHalf*a2[i]));
    b = b1.map((v, i) => F.create(ei*v + e*b2[i]));
    alpha = F.create(alpha + e*e*dL + ei*ei*dR);
  }
  const r = randomScalar(), s = randomScalar(), delta = randomScalar(), eta = randomScalar();
  const A = encodeCommitment(msm([g[0],h[0],U,G], [r,s,y*(r*b[0]+s*a[0]),delta]));
  const B = encodeCommitment(msm([U,G], [r*y*s,eta]));
  const e = hs(sc(transcript), A, B);
  return {left, right, a0, a:A, b:B, r:sc(r+e*a[0]), s:sc(s+e*b[0]), delta:sc(eta+e*delta+e*e*alpha)};
}

function proveAsset(message, ring, index, witness) {
  const m = Math.max(1, Math.ceil(Math.log(ring.length) / Math.log(4)));
  const rows = [], digits = [];
  const rA = randomScalar(), rB = randomScalar();
  let A = X.multiply(rA), B = X.multiply(rB);
  for (let j = 0; j < m; ++j) {
    const digit = (index >> (2*j)) & 3;
    const row = [randomScalar(),randomScalar(),randomScalar()];
    row.unshift(F.create(-row.reduce((a,b) => a+b, 0n)));
    rows.push(row); digits.push(digit);
    for (const [i, v] of row.entries()) {
      const gen = bgeGenerator(8*j + 2*i), aux = bgeGenerator(8*j + 2*i+1);
      A = A.add(msm([gen,aux], [v,-v*v]));
      B = B.add(msm([gen,aux], [BigInt(i === digit), i === digit ? -v : v]));
    }
  }
  const rho = rows.map(randomScalar), coefficients = rho.map(v => X.multiply(v));
  for (let i = 0; i < 4**m; ++i) {
    // Coefficients of product_j (a[j,i_j] + [i_j == l_j] t).
    let polynomial = [1n];
    rows.forEach((row, j) => {
      const digit = (i >> (2*j)) & 3;
      const next = [...polynomial.map(c => F.mul(c, row[digit])), 0n];
      if (digit === digits[j]) polynomial.forEach((c,k) => { next[k+1] = F.add(next[k+1], c); });
      polynomial = next;
    });
    const member = ring[Math.min(i, ring.length-1)];
    coefficients.forEach((p,k) => { coefficients[k] = p.add(member.multiplyUnsafe(polynomial[k])); });
  }
  const a = encodeCommitment(A), b = encodeCommitment(B), pk = coefficients.map(encodeCommitment);
  const x = hs(message, ...ring.map(encodeCommitment), a, b, ...pk);
  const f = rows.flatMap((row,j) => row.slice(1).map((v,i) => sc(v + (i+1 === digits[j] ? x : 0n))));
  let z = witness;
  for (let j = m-1; j >= 0; --j) z = F.create(z*x - rho[j]);
  return {a, b, pk, f, y:sc(rA+x*rB), z:sc(z)};
}

// Each output opening is generated by the builder. The public input masks
// below describe pseudo assets, and never contain a one-time spend secret.
function proveZanoPayment(message, outputs, inputs, txSecret) {
  const amounts = outputs.map(o => o.amount), masks = amounts.map(randomScalar);
  const aggregated = amounts.map((v,i) => msm([U,G],[v,masks[i]]));
  const commitments = aggregated.map(encodeCommitment);
  const prefix = [message, ...outputs.map(o => o.commitment.toBytes()), ...aggregated.map(p => p.toBytes())];
  const w = hs(...prefix), r0 = amounts.map(randomScalar), r1 = amounts.map(randomScalar);
  const nonces = outputs.map((o,i) => msm([o.asset,U,G],[r0[i],r0[i]*w,r1[i]]).toBytes());
  const c = hs(...prefix, ...nonces);
  const aggregation = {commitments, c:sc(c), y0:amounts.map((v,i) => sc(r0[i]-c*v)),
    y1:outputs.map((o,i) => sc(r1[i]-c*(o.amountMask+w*masks[i])))};
  const range = proveRange(amounts, masks, commitments);
  // All inputs and outputs in this builder transfer the native asset.
  const assets = outputs.map(o => proveAsset(message, inputs.map(i => i.pseudoAsset.subtract(o.asset)),
    0, F.sub(inputs[0].pseudoAssetMask, o.assetMask)));
  const secret = F.create(inputs.reduce((v,i) => v + i.assetMask*i.amount, 0n) -
    outputs.reduce((v,o) => v + o.assetMask*o.amount, 0n));
  const k0 = randomScalar(), k1 = randomScalar();
  const balanceChallenge = hs(message, X.multiplyUnsafe(secret).toBytes(), G.multiply(txSecret).toBytes(),
    X.multiply(k0).toBytes(), G.multiply(k1).toBytes());
  const balance = {c:sc(balanceChallenge), y0:sc(k0-balanceChallenge*secret), y1:sc(k1-balanceChallenge*txSecret)};
  return {assets, aggregation, range, balance};
}

module.exports = {proveZanoPayment, encodeCommitment};
