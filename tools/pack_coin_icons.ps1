# Converts assets/icons/32/<ticker>.png into src/generated/CoinIcons.inc.
#
# The trusted panel is monochrome (GDEQ031T10 on the T-Deck Max, 1bpp), so a
# colour logo would be dithered into mush by the panel conversion. Each icon is
# therefore packed as a 32x32 I1 bitmap: 4 bytes per row, MSB first, 128 bytes
# total, and the reviewer paints it through an I1 canvas whose palette is the
# theme's paper and ink - exactly how the QR code is drawn.
#
# Ink selection is adaptive rather than a fixed cut: the threshold is the mean
# luminance of the icon's own opaque pixels, so a bright glyph inside a darker
# disc comes out as a cut-out instead of a blob. If that rule produces an
# unusable silhouette (under 10% or over 90% ink) it falls back to the alpha
# silhouette, and the packer reports it.
#
# Source artwork: https://github.com/spothq/cryptocurrency-icons (CC0 1.0,
# public domain). Run: powershell -ExecutionPolicy Bypass -File tools/pack_coin_icons.ps1
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path -Parent $PSScriptRoot
$size = 32
$stride = 4
$manifestPath = Join-Path $root 'assets/icons/icons.txt'
$artDir = Join-Path $root 'assets/icons/32'

$entries = [Collections.Generic.List[object]]::new()
foreach ($line in [IO.File]::ReadAllLines($manifestPath)) {
  $trimmed = $line.Trim()
  if ($trimmed.Length -eq 0 -or $trimmed.StartsWith('#')) { continue }
  $tokens = $trimmed -split '\s+'
  if ($tokens.Count -lt 2) { throw "Manifest line has no key: $trimmed" }
  $entries.Add([pscustomobject]@{ File = $tokens[0]; Keys = @($tokens[1..($tokens.Count - 1)]) })
}
if ($entries.Count -eq 0) { throw 'The icon manifest is empty.' }

$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by tools/pack_coin_icons.ps1 - do not edit by hand.')
$lines.Add('//')
$lines.Add('// Artwork: cryptocurrency-icons (CC0 1.0), see assets/icons/LICENSE.')
$lines.Add('// Each blob is a 32x32 I1 bitmap: 4 bytes per row, MSB first, 128 bytes.')
$lines.Add('// Bit 1 means "ink" and is painted with the theme foreground, so the same')
$lines.Add('// mask reads correctly on a light or a dark paper colour.')
$lines.Add('')
$records = [Collections.Generic.List[string]]::new()

foreach ($entry in $entries) {
  $name = $entry.File
  $path = Join-Path $artDir "$name.png"
  if (-not (Test-Path -LiteralPath $path)) { throw "Missing artwork: $path" }
  $source = [Drawing.Bitmap]::FromFile($path)
  $canvas = New-Object Drawing.Bitmap $size,$size
  $graphics = [Drawing.Graphics]::FromImage($canvas)
  try {
    $graphics.Clear([Drawing.Color]::Transparent)
    $graphics.InterpolationMode = [Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $graphics.PixelOffsetMode = [Drawing.Drawing2D.PixelOffsetMode]::HighQuality
    $graphics.DrawImage($source, [Drawing.Rectangle]::new(0,0,$size,$size))
    $luma = New-Object int[] ($size * $size)
    $opaque = New-Object bool[] ($size * $size)
    $sum = 0.0
    $count = 0
    for ($y = 0; $y -lt $size; ++$y) {
      for ($x = 0; $x -lt $size; ++$x) {
        $pixel = $canvas.GetPixel($x,$y)
        $index = $y * $size + $x
        $opaque[$index] = ($pixel.A -ge 128)
        $luma[$index] = [int](0.299 * $pixel.R + 0.587 * $pixel.G + 0.114 * $pixel.B)
        if ($opaque[$index]) { $sum += $luma[$index]; $count++ }
      }
    }
    if ($count -lt ($size * $size) / 5) { throw "$name covers only $count opaque pixels; the artwork is probably wrong" }
    $mean = $sum / $count
    $mask = New-Object byte[] ($stride * $size)
    $ink = 0
    for ($y = 0; $y -lt $size; ++$y) {
      for ($x = 0; $x -lt $size; ++$x) {
        $index = $y * $size + $x
        if (-not $opaque[$index]) { continue }
        if ($luma[$index] -lt $mean) {
          $mask[$y * $stride + [math]::Floor($x / 8)] = $mask[$y * $stride + [math]::Floor($x / 8)] -bor (0x80 -shr ($x % 8))
          $ink++
        }
      }
    }
    # A logo that is a single flat colour has no internal contrast, so the mean
    # threshold leaves nothing. Fall back to the alpha silhouette instead of
    # shipping an empty square.
    $coverage = $ink * 100 / ($size * $size)
    if ($coverage -lt 10 -or $coverage -gt 90) {
      $mask = New-Object byte[] ($stride * $size)
      $ink = 0
      for ($y = 0; $y -lt $size; ++$y) {
        for ($x = 0; $x -lt $size; ++$x) {
          if (-not $opaque[$y * $size + $x]) { continue }
          $mask[$y * $stride + [math]::Floor($x / 8)] = $mask[$y * $stride + [math]::Floor($x / 8)] -bor (0x80 -shr ($x % 8))
          $ink++
        }
      }
      $coverage = $ink * 100 / ($size * $size)
      Write-Output ("note: {0} has no internal contrast, using the silhouette ({1:N0}% ink)" -f $name, $coverage)
    }
    if ($ink -eq 0) { throw "$name produced an empty mask" }
  } finally {
    $graphics.Dispose()
    $canvas.Dispose()
    $source.Dispose()
  }
  $identifier = 'kCoinIconArt' + ($name.Substring(0,1).ToUpper() + $name.Substring(1))
  $lines.Add("static const uint8_t ${identifier}[$($mask.Length)] = {")
  for ($i = 0; $i -lt $mask.Length; $i += 16) {
    $end = [math]::Min($i + 15, $mask.Length - 1)
    $lines.Add('    ' + (($mask[$i..$end] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', ') + ',')
  }
  $lines.Add('};')
  $lines.Add('')
  foreach ($key in $entry.Keys) {
    $records.Add("    {`"$key`", $identifier, $($mask.Length)},")
  }
  Write-Output ("packed {0} ({1} keys, {2:N0}% ink)" -f $name, $entry.Keys.Count, $coverage)
}

$lines.Add('// Exact, case-sensitive keys: a near miss shows no logo rather than the wrong')
$lines.Add('// one, and the caller never has to trust a fuzzy match.')
$lines.Add('static const CoinIcon kCoinIconTable[] = {')
foreach ($record in $records) { $lines.Add($record) }
$lines.Add('};')

$out = Join-Path $root 'src/generated/CoinIcons.inc'
[IO.File]::WriteAllText($out, (($lines -join "`n") + "`n"), [Text.UTF8Encoding]::new($false))
Write-Output ("wrote src/generated/CoinIcons.inc ({0} keys, {1} icons)" -f $records.Count, $entries.Count)