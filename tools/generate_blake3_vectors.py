#!/usr/bin/env python3
"""Turn the official BLAKE3 test vectors into pinned C++ includes.

The source file is a verbatim copy of BLAKE3-team/BLAKE3
`test_vectors/test_vectors.json`. Nothing here computes a hash: the script only
re-encodes data that upstream publishes, so a mismatch found by the host suite
is a mismatch against upstream, not against this repository.

Each case carries three 131-byte outputs (hash, keyed_hash, derive_key). 131 is
`2 * BLOCK_LEN + 3` on purpose: it is not a multiple of 4, so a partial-word bug
in the extended output function shows up instead of hiding behind truncation.

Two includes are written:

* `Blake3VectorsTest.inc` - every case, linked into the host build only.
* `Blake3Kat.inc`         - three cases (0, 65 and 1024 bytes: empty, one block
  plus one byte, and exactly one chunk), small enough to keep in the firmware so
  the device can verify its own compression function at boot.
"""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools/blake3_test_vectors.json"
FULL_OUTPUT = ROOT / "src/generated/Blake3VectorsTest.inc"
DEVICE_OUTPUT = ROOT / "src/generated/Blake3Kat.inc"

OUTPUT_LEN = 131
DEVICE_CASES = (0, 65, 1024)


def hex_bytes(text):
    if len(text) != OUTPUT_LEN * 2:
        raise ValueError(f"expected {OUTPUT_LEN} bytes, got {len(text) // 2}")
    return bytes.fromhex(text)


def emit_array(name, comment, values):
    lines = [f"// {comment}", f"static const uint8_t {name}[kBlake3TestCount][{OUTPUT_LEN}] = {{"]
    for index, row in enumerate(values):
        lines.append(f"    {{  // case {index}")
        for start in range(0, OUTPUT_LEN, 16):
            chunk = ", ".join(f"0x{byte:02x}" for byte in row[start:start + 16])
            lines.append(f"        {chunk},")
        lines.append("    },")
    lines.append("};")
    return lines


def render(device_only):
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    cases = data["cases"]
    key = data["key"].encode("ascii")
    if len(key) != 32:
        raise ValueError("the BLAKE3 key must be 32 bytes")
    lengths = [case["input_len"] for case in cases]
    if lengths != sorted(lengths) or len(set(lengths)) != len(lengths):
        raise ValueError("input lengths must be unique and sorted")
    if device_only:
        missing = [length for length in DEVICE_CASES if length not in lengths]
        if missing:
            raise ValueError(f"device KAT lengths absent upstream: {missing}")
        cases = [cases[lengths.index(length)] for length in DEVICE_CASES]
        lengths = list(DEVICE_CASES)
    if not cases:
        raise ValueError("no cases selected")

    hashes = [hex_bytes(case["hash"]) for case in cases]
    keyed = [hex_bytes(case["keyed_hash"]) for case in cases]
    derived = [hex_bytes(case["derive_key"]) for case in cases]

    header = [
        "// Generated by tools/generate_blake3_vectors.py from the official",
        "// BLAKE3-team/BLAKE3 test_vectors/test_vectors.json. Do not edit.",
        "// Every expected output is OUTPUT_LEN = 2 * BLOCK_LEN + 3 = 131 bytes, so the",
        "// extended output function is pinned and not only its first block.",
        "// Inputs are the repeating 251-byte cycle 0, 1, ... 250, 0, ...",
        "// Device KAT subset: empty input, block+1, and one full chunk."
        if device_only
        else "// Full official set, host build only.",
        "",
        f"static const size_t kBlake3TestCount = {len(cases)};",
        "static const size_t kBlake3TestOutputLen = 131;",
        "static const uint32_t kBlake3TestInputLengths[kBlake3TestCount] = {",
        "    " + ", ".join(str(length) for length in lengths),
        "};",
        "",
        "static const uint8_t kBlake3TestKey[32] = {",
        "    " + ", ".join(f"0x{byte:02x}" for byte in key),
        "};",
        "static const char kBlake3TestContext[] =",
        f'    "{data["context_string"]}";',
        "",
    ]
    body = emit_array("kBlake3TestHash", "Unkeyed hash mode.", hashes)
    body += [""]
    body += emit_array("kBlake3TestKeyedHash", "Keyed hash mode.", keyed)
    body += [""]
    body += emit_array("kBlake3TestDeriveKey", "derive_key mode with the context above.", derived)
    return "\n".join(header + body) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        FULL_OUTPUT: render(device_only=False),
        DEVICE_OUTPUT: render(device_only=True),
    }
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, content in outputs.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != content]
        if stale:
            raise SystemExit("stale generated files: " + ", ".join(stale))
        print("blake3 vectors: check=pass")
        return
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8", newline="\n")
    print("blake3 vectors: wrote " + ", ".join(str(path.relative_to(ROOT)) for path in outputs))


if __name__ == "__main__":
    main()
