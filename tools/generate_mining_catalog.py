"""Resolve a pinned MiningPoolStats snapshot against the compiled wallet catalog.

This tool never guesses a network from a ticker, mining algorithm or address
prefix. The reviewed source-ID mapping is the only admission path. Website
metadata is data, never executable JavaScript or a signing-policy source.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
TYPES = {"ASIC": "Asic", "GPU": "Gpu", "CPU": "Cpu", "HDD": "Hdd", "MERGED": "Merged"}


def read_json(path):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"duplicate JSON key: {key}")
            result[key] = value
        return result
    return json.loads(path.read_text(encoding="utf-8-sig"), object_pairs_hook=unique)


def snapshot_digest(snapshot):
    # Stable across Git LF/CRLF conversion and JSON whitespace changes.
    canonical = json.dumps(snapshot, sort_keys=True, ensure_ascii=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("ascii")).hexdigest()


def active_rows(snapshot):
    result = {}
    graveyard = snapshot["GRAVEYARD"]
    if not isinstance(graveyard, dict) or not graveyard:
        raise ValueError("missing GRAVEYARD data")
    for group, coins in snapshot.items():
        if group in ("time", "GRAVEYARD"):
            continue
        category, separator, algorithm = group.partition(" - ")
        if group == "MERGED Mining":
            category, separator, algorithm = "MERGED", " - ", "Merged mining"
        if category not in TYPES or not separator or not isinstance(coins, dict):
            raise ValueError(f"unknown category: {group}")
        for slug, coin in coins.items():
            if slug in result or slug in graveyard:
                raise ValueError(f"duplicate/retired source ID: {slug}")
            if not slug or any(c not in "abcdefghijklmnopqrstuvwxyz0123456789_-" for c in slug):
                raise ValueError(f"invalid source ID: {slug}")
            name, symbol = coin["n"].strip(), coin["s"].strip()
            algo = coin.get("a", algorithm).strip()
            if any(not text or not text.isprintable() for text in (name, symbol, algo)):
                raise ValueError(f"invalid display metadata: {slug}")
            result[slug] = dict(name=name, symbol=symbol, algorithm=algo, type=TYPES[category])
    if not result:
        raise ValueError("empty active snapshot")
    return result


def catalog_rows(output):
    rows = {}
    for line in output.splitlines():
        fields = line.split("|", 6)
        if len(fields) != 7 or fields[0] in rows or not fields[0] or not fields[4]:
            raise ValueError(f"invalid compiled catalog row: {line}")
        key, symbol, name, caps, network, domain, scope = fields
        bits = int(caps)
        if bits < 0 or bits > 15 or bits & 4 and not bits & 2:
            raise ValueError(f"inconsistent catalog capability: {key}")
        rows[key] = dict(symbol=symbol, name=name, caps=bits, network=network,
                         domain=domain, scope=scope)
    if not rows:
        raise ValueError("empty compiled catalog")
    return rows


def resolve(active, mappings, catalog):
    resolved = {}
    for slug, binding in mappings.items():
        if slug not in active:
            raise ValueError(f"mapping no longer active: {slug}")
        coin = active[slug]
        if (binding["symbol"], binding["name"]) != (coin["symbol"], coin["name"]):
            raise ValueError(f"source identity changed: {slug}")
        target = binding["catalog_id"]
        if target not in catalog:
            raise ValueError(f"catalog entry missing: {slug} -> {target}")
        entry = catalog[target]
        if entry["symbol"] != coin["symbol"] or not entry["caps"] & 1:
            raise ValueError(f"native asset mismatch: {slug} -> {target}")
        resolved[slug] = (target, entry)
    return resolved


def render(active, resolved, metadata):
    include = ["// Generated by tools/generate_mining_catalog.py; do not edit.",
               "// Active, explicitly mapped native assets only. Capability comes from WalletCatalog."]
    for slug in sorted(resolved, key=lambda s: (active[s]["type"], active[s]["name"].casefold(), s)):
        coin = active[slug]
        quoted = [json.dumps(coin[k], ensure_ascii=True) for k in ("symbol", "name", "algorithm")]
        include.append("  {" + ", ".join(quoted) + f', MiningCoinType::{coin["type"]}, '
                       + json.dumps(slug) + ", " + json.dumps(resolved[slug][0]) + "},")
    mapped = {target for target, _ in resolved.values()}
    signable = {target for target, row in resolved.values() if row["caps"] & 4}
    report = ["# MiningPoolStats coverage", "",
              "Generated by `tools/generate_mining_catalog.py`. Do not edit by hand.", "",
              f'Snapshot: [{metadata["checked_date"]}]({metadata["source"]}).', "",
              f'Active mining entries: {len(active)}; mapped entries: {len(resolved)}; '
              f'unmapped entries: {len(active) - len(resolved)}.',
              f'Distinct mapped wallet profiles: {len(mapped)}; profiles declaring a signing path: {len(signable)}.', "",
              "Mining entries include algorithm variants. Neither entries nor profiles are a count of fully supported blockchains.",
              "SIGN is the compiled catalog's code capability, not node acceptance, complete protocol coverage or hardware certification. "
              "ADDRESS has no admitted signing path. UNMAPPED is not supported by this directory. "
              "No inference is made from a shared ticker, mining algorithm or EVM-compatible address.", "",
              "| Source ID | Native asset | Wallet profile | Code capability | Implemented scope |",
              "| --- | --- | --- | --- | --- |"]
    def cell(value):
        return str(value).replace("|", "\\|").replace("\r", " ").replace("\n", " ")
    for slug in sorted(active):
        coin = active[slug]
        target, row = resolved.get(slug, ("—", None))
        cap = "UNMAPPED" if row is None else "SIGN" if row["caps"] & 4 else "ADDRESS"
        scope = "No explicit native-network mapping" if row is None else row["scope"]
        report.append("| " + " | ".join(map(cell, (slug, coin["symbol"] + " / " + coin["name"], target, cap, scope))) + " |")
    # Ambiguity includes unsupported projects too. A missing adapter must not
    # make a shared ticker appear unique and select a different asset.
    aliases = {}
    for coin in active.values():
        identity = (coin["symbol"].casefold(), coin["name"].casefold())
        for alias in identity:
            aliases.setdefault(alias, set()).add(identity)
    ambiguous = ["// Generated from every active source identity, including unmapped assets."]
    ambiguous += ["  " + json.dumps(alias, ensure_ascii=True) + ","
                  for alias, identities in sorted(aliases.items()) if len(identities) > 1]
    return "\n".join(include) + "\n", "\n".join(report) + "\n", "\n".join(ambiguous) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=ROOT / "tests/host/catalog_dump.exe")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    snapshot_path = ROOT / "tools/miningpoolstats_coin_list.json"
    metadata = read_json(ROOT / "tools/miningpoolstats_snapshot.json")
    snapshot = read_json(snapshot_path)
    if snapshot_digest(snapshot) != metadata["canonical_sha256"]:
        raise ValueError("snapshot hash differs from reviewed manifest")
    graveyard = read_json(ROOT / "tools/miningpoolstats_graveyard.json")
    if graveyard["coins"] != snapshot["GRAVEYARD"] or graveyard["source"] != metadata["source"]:
        raise ValueError("GRAVEYARD and active snapshot disagree")
    active = active_rows(snapshot)
    output = subprocess.run([str(args.catalog.resolve()), "--native"], check=True,
                            capture_output=True, text=True, encoding="utf-8").stdout
    resolved = resolve(active, read_json(ROOT / "tools/miningpoolstats_mapping.json"), catalog_rows(output))
    include, report, ambiguous = render(active, resolved, metadata)
    for relative, content in (("src/generated/WalletMiningCatalog.inc", include),
                              ("wiki/miningpoolstats-coverage.md", report),
                              ("src/generated/WalletMiningAmbiguousAliases.inc", ambiguous)):
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise ValueError(f"stale generated file: {relative}")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    print(f"mining catalog: {len(active)} active entries, {len(resolved)} mapped; check={'pass' if args.check else 'generated'}")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        raise SystemExit(str(error)) from error
