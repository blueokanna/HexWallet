#!/usr/bin/env python3
"""Generate the MiningPoolStats coverage catalog shipped with the firmware."""
from __future__ import annotations

import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from miningpool_coverage import fetch_coins

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "src/generated/WalletMiningCatalog.inc"
TYPES = {"ASIC": "Asic", "GPU": "Gpu", "CPU": "Cpu", "HDD": "Hdd"}


def cpp_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def catalog_entries() -> list[tuple[str, str, str]]:
    entries: list[tuple[str, str, str]] = []
    for name in ("WalletCatalog.cpp", "src/generated/WalletForkCatalog.inc"):
        text = (ROOT / name).read_text(encoding="utf-8")
        for match in re.finditer(
                r'\{\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)"', text):
            entries.append(match.groups())
    return entries


def normalized_name(value: str) -> str:
    name = value.strip().lower()
    for suffix in (" native segwit", " nested segwit", " legacy"):
        if name.endswith(suffix):
            return name[:-len(suffix)]
    return name


def pick_catalog_id(coin: dict, entries: list[tuple[str, str, str]]) -> str | None:
    symbol = (coin.get("symbol") or "").upper()
    name = normalized_name(coin.get("name") or "")
    matches = [item for item in entries if normalized_name(item[2]) == name]
    for item in matches:
        if item[1].upper() == symbol:
            return item[0]
    if matches:
        return matches[0][0] if len(matches) == 1 else None
    coin_first = name.split()[0]
    for item in entries:
        if item[1].upper() != symbol:
            continue
        if normalized_name(item[2]).split()[0] == coin_first:
            return item[0]
    return None


def main() -> int:
    coins = [coin for coin in fetch_coins() if coin.get("typ") in TYPES]
    entries = catalog_entries()
    rows = {}
    for coin in coins:
        symbol = (coin.get("symbol") or "").strip()
        name = (coin.get("name") or "").strip()
        algorithm = (coin.get("algo") or "").strip()
        if not symbol or not name or not algorithm:
            continue
        key = (symbol.upper(), name.lower(), algorithm.lower(), coin["typ"])
        rows[key] = {
            "symbol": symbol,
            "name": name,
            "algorithm": algorithm,
            "type": coin["typ"],
            "catalog_id": pick_catalog_id(coin, entries),
            "market_cap": float(coin.get("mc") or 0),
        }

    supported_rows = [row for row in rows.values() if row["catalog_id"]]
    order = {"ASIC": 0, "GPU": 1, "CPU": 2, "HDD": 3}
    output = [
        "// Generated by tools/generate_mining_catalog.py from MiningPoolStats.",
        "// Only chains with an exposed receive/send/sign catalog entry are listed.",
    ]
    for row in sorted(supported_rows, key=lambda item: (
            order[item["type"]], item["symbol"].upper(), item["name"].lower(),
            item["algorithm"].lower())):
        output.append(
            f'  {{{cpp_string(row["symbol"])}, {cpp_string(row["name"])}, '
            f'{cpp_string(row["algorithm"])}, MiningCoinType::{TYPES[row["type"]]}, '
            f'{cpp_string(row["catalog_id"])}}},'
        )
    OUT.write_text("\n".join(output) + "\n", encoding="utf-8")
    print(f"generated {len(supported_rows)} supported mining rows; "
          f"dropped {len(rows) - len(supported_rows)} unsupported listings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
