"""Reproduce the LVGL Chinese subset from pinned OFL Noto Sans CJK SC."""
import argparse
import hashlib
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT_SHA256 = "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b"


def characters():
    text = (ROOT / "WalletUi.cpp").read_text(encoding="utf-8")
    text += (ROOT / "src/UiText.inc").read_text(encoding="utf-8")
    text += (ROOT / "src/generated/PinyinDictionary.inc").read_text(encoding="utf-8")
    text += (ROOT / "src/generated/Bip39Chinese.inc").read_text(encoding="utf-8")
    return "".join(sorted({c for c in text if ord(c) > 127}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=ROOT / "build/ui-font/NotoSansCJKsc-Regular.otf")
    parser.add_argument("--converter", type=Path, default=ROOT / "build/ui-font/node_modules/lv_font_conv/lv_font_conv.js")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    dest = ROOT / "src/generated/UiChineseFont.inc"
    symbols = characters()
    manifest = ROOT / "assets/fonts/ui-characters.txt"
    if hashlib.sha256(args.font.read_bytes()).hexdigest() != FONT_SHA256:
        raise SystemExit("Unexpected source font digest")
    version = args.converter.parent / "package.json"
    import json
    if json.loads(version.read_text())["version"] != "1.5.3":
        raise SystemExit("Use lv_font_conv 1.5.3")
    # Check by regeneration in a scratch directory without modifying the checked-in
    # font. A character manifest alone cannot detect changed or stale glyph data.
    with tempfile.TemporaryDirectory(prefix="font-check-", dir=args.font.parent) as scratch:
        generated = Path(scratch) / dest.name
        subprocess.run(["node", str(args.converter), "--font", str(args.font), "--symbols", symbols,
                        "--size", "14", "--bpp", "1", "--format", "lvgl", "--no-compress", "--no-kerning",
                        "--lv-font-name", "hexwallet_ui_chinese", "--lv-include", "lvgl.h", "-o", str(generated)], check=True)
        text = generated.read_text(encoding="utf-8")
    # Paths and command arguments in the generated comment are machine-specific.
    text = re.sub(r"/\*\*\*.*?\*/", "/* Generated by tools/generate_ui_font.py; Noto Sans CJK SC, OFL-1.1. */", text, count=1, flags=re.S)
    text = text.replace(".fallback = NULL", ".fallback = &lv_font_montserrat_12")
    # Give the 14px CJK glyphs and the 15px ASCII fallback a shared 16px line.
    text = re.sub(r"\.line_height = \d+", ".line_height = 16", text)
    text = re.sub(r"\.base_line = \d+", ".base_line = 3", text)
    if args.check:
        if manifest.read_bytes() != (symbols + "\n").encode("utf-8") or dest.read_bytes() != text.encode("utf-8"):
            raise SystemExit("Chinese strings or generated glyph data changed: regenerate the font")
        print(f"Chinese font reproduced byte-for-byte; {len(symbols)} glyphs; pinned source and converter verified")
        return
    dest.write_text(text, encoding="utf-8", newline="\n")
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(symbols + "\n", encoding="utf-8", newline="\n")
    print(f"Generated {len(symbols)} Chinese/punctuation glyphs, ASCII uses Montserrat 12")


if __name__ == "__main__":
    main()
