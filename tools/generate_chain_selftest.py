"""Embed immutable SDK fixtures; no firmware output is used as an oracle."""
from pathlib import Path
import json
import sys
ROOT = Path(__file__).resolve().parents[1]
vectors = json.loads((ROOT/'tests/fixtures/chain-sdk.json').read_text(encoding='utf8'))
def array(name, text):
    values = bytes.fromhex(text)
    lines = [', '.join(f'0x{v:02x}' for v in values[i:i+12]) for i in range(0,len(values),12)]
    return f'static const uint8_t {name}[] = {{\n  ' + ',\n  '.join(lines) + '\n};\n'
outputs = {}
dot = vectors['dotSelftest']
outputs['PolkadotVectorsTest.inc'] = array('kExpectedDigest',dot['hash']) + array('kExpectedSigned',dot['signed'])
for name, network in [('Sui','sui'),('Filecoin','fil')]:
    c = next(c for c in vectors['cases'] if c['network']==network)
    text = array('kPayload',c['payload']) + array('kExpectedDigest',c['hash'])
    if network=='sui': text += array('kExpectedSigned',c['signed'])
    for key in ['address','recipient','amount','fee']:
        text += f'static const char k{key.title()}[] = {json.dumps(c[key])};\n'
    outputs[f'{name}VectorsTest.inc'] = text
for name,text in outputs.items():
    target=ROOT/'src/generated'/name
    text='// Generated by tools/generate_chain_selftest.py from independent SDK fixtures.\n'+text
    if '--check' in sys.argv:
        if not target.exists() or target.read_text(encoding='utf8')!=text:
            raise SystemExit(f'stale {target}')
    else: target.write_text(text,encoding='utf8')
