#!/usr/bin/env python3
"""Regenerate ZcashZip243VectorsTest.inc from the official ZIP-243 vectors.

Source: https://github.com/zcash/zcash-test-vectors/blob/master/test-vectors/json/zip_0243.json
The in-tree JSON is kept so the checked-in .inc can be audited offline.
Rows 2-4 and 11 add shielded spends, shielded outputs, JoinSplits and the
SIGHASH_SINGLE/NONE paths to the transparent ZIP-243 test vector that the
firmware checks at boot.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools" / "zcash_zip243_vectors.json"
OUTPUT = ROOT / "src/generated/ZcashZip243VectorsTest.inc"
ROWS = (2, 3, 4, 11)


def byte_array(name, data):
    lines = [f"static const uint8_t {name}[] = {{"]
    for offset in range(0, len(data), 12):
        chunk = ", ".join(f"0x{value:02x}" for value in data[offset:offset + 12])
        lines.append(f"  {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    vectors = json.loads(SOURCE.read_text())
    out = [
        "// Generated by tools/generate_zcash_zip243_vectors.py from",
        "// zcash/zcash-test-vectors test-vectors/json/zip_0243.json.",
        "// Selected rows cover shielded spends, shielded outputs and JoinSplits",
        "// in addition to the transparent vector published in ZIP-243.",
    ]
    for row_index in ROWS:
        row = vectors[row_index]
        tx = bytes.fromhex(row[0])
        script = bytes.fromhex(row[1])
        out.append(
            f"// zip_0243.json row {row_index}: transparent_input={row[2]}, "
            f"hash_type={row[3]}, branch=0x{row[5]:08x}"
        )
        out.append(byte_array(f"kZip243Tx{row_index}", tx))
        if script:
            out.append(byte_array(f"kZip243Script{row_index}", script))
        else:
            out.append(f"static const uint8_t kZip243Script{row_index}[1] = {{ 0 }};")
        digest = ", ".join(f"0x{value:02x}" for value in bytes.fromhex(row[6]))
        out.append(f"static const uint8_t kZip243Digest{row_index}[32] = {{ {digest} }};")
    out.extend([
        "struct ZcashSighashVector {",
        "  const char *name;",
        "  const uint8_t *transaction;",
        "  size_t transaction_size;",
        "  const uint8_t *script_code;",
        "  size_t script_code_size;",
        "  int32_t input_index;",
        "  uint32_t hash_type;",
        "  uint64_t amount;",
        "  uint32_t branch_id;",
        "  const uint8_t *digest;",
        "};",
        "static const ZcashSighashVector kZip243Vectors[] = {",
    ])
    for row_index in ROWS:
        row = vectors[row_index]
        out.append(
            f'  {{ "zip243-row{row_index}", kZip243Tx{row_index}, '
            f"sizeof(kZip243Tx{row_index}), kZip243Script{row_index}, "
            f"{len(bytes.fromhex(row[1]))}, {row[2]}, {row[3]}U, "
            f"{row[4]}ULL, 0x{row[5]:08x}U, kZip243Digest{row_index} }},"
        )
    out.append("};")
    OUTPUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
