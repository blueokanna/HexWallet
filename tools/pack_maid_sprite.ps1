# Asset conversion only: firmware has no image decoder or filesystem dependency.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path -Parent $PSScriptRoot
$source = [Drawing.Bitmap]::FromFile((Join-Path $root 'assets/mascot/deepseek-maid-sheet.png'))
$preview = New-Object Drawing.Bitmap 1024,512
$previewGraphics = [Drawing.Graphics]::FromImage($preview)
$previewGraphics.Clear([Drawing.Color]::White)
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by tools/pack_maid_sprite.ps1; eight 64x64 MSB-first 1bpp frames.')
$lines.Add('static const uint8_t kMaidFrames[8][512] = {')
try {
  for ($frame = 0; $frame -lt 8; ++$frame) {
    $tile = New-Object Drawing.Bitmap 64,64
    $graphics = [Drawing.Graphics]::FromImage($tile)
    try {
      $graphics.Clear([Drawing.Color]::White)
      $graphics.InterpolationMode = [Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
      $graphics.DrawImage($source, [Drawing.Rectangle]::new(0,0,64,64),
        [single](($frame % 4) * $source.Width / 4), [single]([math]::Floor($frame / 4) * $source.Height / 2),
        [single]($source.Width / 4), [single]($source.Height / 2), [Drawing.GraphicsUnit]::Pixel)
      $bytes = New-Object byte[] 512
      for ($y = 0; $y -lt 64; ++$y) {
        for ($x = 0; $x -lt 64; ++$x) {
          $pixel = $tile.GetPixel($x,$y)
          if ((299 * $pixel.R + 587 * $pixel.G + 114 * $pixel.B) -lt 160000) {
            $offset = $y * 8 + [math]::Floor($x / 8)
            $bytes[$offset] = $bytes[$offset] -bor (128 -shr ($x % 8))
            $previewGraphics.FillRectangle([Drawing.Brushes]::Black,
              [int](($frame % 4)*256 + $x*4), [int]([math]::Floor($frame/4)*256 + $y*4), 4, 4)
          }
        }
      }
      $lines.Add('  {')
      for ($i = 0; $i -lt 512; $i += 16) {
        $lines.Add('    ' + (($bytes[$i..($i+15)] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', ') + ',')
      }
      $lines.Add('  },')
    } finally { $graphics.Dispose(); $tile.Dispose() }
  }
  $lines.Add('};')
  [IO.File]::WriteAllLines((Join-Path $root 'src/generated/MaidSprite.inc'), $lines, [Text.UTF8Encoding]::new($false))
  $preview.Save((Join-Path $root 'assets/mascot/deepseek-maid-preview.png'), [Drawing.Imaging.ImageFormat]::Png)
} finally { $previewGraphics.Dispose(); $preview.Dispose(); $source.Dispose() }
