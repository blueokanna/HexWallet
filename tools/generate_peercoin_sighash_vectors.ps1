# Independent public-data oracle; no wallet keys or firmware code are executed.
# Consensus layout: peercoin/peercoin src/script/interpreter.cpp,
# CTransactionSignatureSerializer::Serialize and SignatureHash(WITNESS_V0).
# Versions 1/2 serialize nTime after nVersion; version 3 omits it.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
function LE32([uint32]$v) { return [BitConverter]::GetBytes($v) }
function LE64([uint64]$v) { return [BitConverter]::GetBytes($v) }
function Hash256([byte[]]$bytes) {
  $sha = [Security.Cryptography.SHA256]::Create()
  try { return $sha.ComputeHash($sha.ComputeHash($bytes)) } finally { $sha.Dispose() }
}
# HASH160 of compressed secp256k1 generator; fixed independently of firmware.
[byte[]]$code = @(0x76,0xa9,0x14,0x75,0x1e,0x76,0xe8,0x19,0x91,0x96,0xd4,0x54,
  0x94,0x1c,0x45,0xd1,0xb3,0xa3,0x23,0xf1,0x43,0x3b,0xd6,0x88,0xac)
$prevouts = @(); $sequences = @(); $outputs = @()
for ($i = 0; $i -lt 2; ++$i) {
  $prevouts += [byte[]](($i*32)..($i*32+31)) + (LE32 $i)
  $sequences += LE32 ([uint32](4294967293 - $i))
  $outputs += (LE64 (1000000 + $i*2000000)) + [byte[]]@(25,0x76,0xa9,0x14) +
      [byte[]](@(0x11+$i)*20) + [byte[]]@(0x88,0xac)
}
$lines = @('// Generated by tools/generate_peercoin_sighash_vectors.ps1.',
  '// Indexed by version-1, witness-v0, input index; raw SHA256d byte order.',
  'static const uint8_t kPeercoinDigests[3][2][2][32] = {')
for ($version = 1; $version -le 3; ++$version) {
  $lines += '  {'
  [byte[]]$header = LE32 $version
  if ($version -lt 3) { $header += LE32 1700000000 }
  for ($witness = 0; $witness -lt 2; ++$witness) {
    $lines += '    {'
    for ($index = 0; $index -lt 2; ++$index) {
      [byte[]]$preimage = $header
      if ($witness) {
        $preimage += (Hash256 $prevouts) + (Hash256 $sequences) +
            [byte[]](($index*32)..($index*32+31)) + (LE32 $index) +
            [byte[]]@(25) + $code + (LE64 (2000000 + $index*1000000)) +
            (LE32 ([uint32](4294967293 - $index))) + (Hash256 $outputs)
      } else {
        $preimage += [byte[]]@(2)
        for ($i = 0; $i -lt 2; ++$i) {
          $preimage += [byte[]](($i*32)..($i*32+31)) + (LE32 $i)
          if ($i -eq $index) { $preimage += [byte[]]@(25) + $code }
          else { $preimage += [byte[]]@(0) }
          $preimage += LE32 ([uint32](4294967293 - $i))
        }
        $preimage += [byte[]]@(2) + $outputs
      }
      $preimage += (LE32 12345) + (LE32 1)
      $hex = ((Hash256 $preimage) | ForEach-Object { '0x{0:x2}' -f $_ }) -join ','
      $lines += "      {$hex},"
    }
    $lines += '    },'
  }
  $lines += '  },'
}
$lines += '};'
[IO.File]::WriteAllLines((Join-Path $root 'src/generated/PeercoinSighashVectors.inc'),
  $lines, (New-Object Text.UTF8Encoding $false))
