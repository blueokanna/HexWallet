"""Generate offline single-syllable pinyin input from pypinyin 0.55.0 (MIT).

Install into build/input-dictionary; the output covers GB2312 Han characters
and both Chinese BIP39 lists. No prediction service or input telemetry exists.
"""
from collections import defaultdict
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "build/input-dictionary"))
import pypinyin

assert pypinyin.__version__ == "0.55.0"
chars = set()
for lead in range(0xb0, 0xf8):
    for trail in range(0xa1, 0xff):
        try:
            text = bytes([lead, trail]).decode("gb2312")
            if 0x4e00 <= ord(text) <= 0x9fff:
                chars.add(text)
        except UnicodeDecodeError:
            pass
for name in ("chinese_simplified", "chinese_traditional"):
    chars.update((ROOT / f"assets/wordlists/{name}.txt").read_text(encoding="utf-8").splitlines())
dictionary = defaultdict(set)
for char in sorted(chars):
    for syllable in pypinyin.pinyin(char, style=pypinyin.Style.NORMAL, heteronym=True)[0]:
        if syllable.isascii() and syllable.isalpha() and len(syllable) <= 7:
            dictionary[syllable].add(char)
lines = ["// Generated by tools/generate_input_dictionary.py; pypinyin 0.55.0 (MIT).",
         "struct PinyinEntry { const char *syllable; const char *characters; };",
         "static const PinyinEntry kPinyinDictionary[] = {"]
for syllable, candidates in sorted(dictionary.items()):
    lines.append('  {"' + syllable + '", "' + ''.join(sorted(candidates)) + '"},')
lines.append("};")
(ROOT / "src/generated/PinyinDictionary.inc").write_text('\n'.join(lines) + '\n', encoding="utf-8")
(ROOT / "assets/fonts/pinyin-LICENSE.txt").write_bytes((ROOT / "build/input-dictionary/pypinyin-0.55.0.dist-info/licenses/LICENSE.txt").read_bytes())
print(f"pinyin-syllables={len(dictionary)} supported-Han={len(set.union(*dictionary.values()))}")
